#!/usr/bin/env python3
"""Builds the vector test content for the processor screens.

    python3 tools/vector_test_cards.py

Writes, from the bundled DejaVu Sans Mono Bold (fonts/, licence beside it):
  content/glyphs.js                   glyph outlines for the counters drawn on the panel
  content/test-card.svg               an awkward four-value test card: curves, arcs, thin
                                      strokes, holes, both fill rules, overlaps, small text
  content/test-star.svg               a Siemens star, turned by the app to show the crystal's response
  content/test-card-off-palette.svg   the same card breaking the rule on purpose: a fifth
                                      grey and a gradient, which the processor must refuse

Every colour on the cards is one of the four drive greys: 255, 170, 85, 0.
Text is converted to outlines here, so the cards need no font at run time.
"""
import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

APP = Path(__file__).resolve().parent.parent
FONT = TTFont('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf')
GLYPHS = FONT.getGlyphSet()
CMAP = FONT.getBestCmap()
UPM = FONT['head'].unitsPerEm


def glyph_path(ch, x=0.0, y=0.0, size=None):
    """Outline of one character as path data, y down. With size: in units where
    the em is `size` tall, placed with its baseline origin at (x, y)."""
    name = CMAP[ord(ch)]
    pen = SVGPathPen(GLYPHS)
    s = 1.0 if size is None else size / UPM
    GLYPHS[name].draw(TransformPen(pen, (s, 0, 0, -s, x, y)))
    return pen.getCommands(), GLYPHS[name].width * s


def text_path(text, x, y, size, spacing=0.0):
    d, pen_x = [], x
    for ch in text:
        if ch != ' ':
            commands, advance = glyph_path(ch, pen_x, y, size)
            d.append(commands)
        else:
            advance = GLYPHS[CMAP[ord(' ')]].width * size / UPM
        pen_x += advance + spacing
    return ' '.join(d), pen_x - x


# ---------------------------------------------------------------------------
# Glyph outlines for the counters (font units, y down from the baseline)
# ---------------------------------------------------------------------------

def write_glyphs():
    chars = '0123456789LINES'
    glyphs = {}
    for ch in chars:
        d, advance = glyph_path(ch)
        glyphs[ch] = {'advance': advance, 'd': d}
    glyphs[' '] = {'advance': GLYPHS[CMAP[ord(' ')]].width, 'd': ''}
    body = json.dumps({'unitsPerEm': UPM, 'glyphs': glyphs}, separators=(',', ':'))
    (APP / 'content' / 'glyphs.js').write_text(
        '/* Glyph outlines for the text drawn on vector-input screens (the counters).\n'
        ' * Generated by tools/vector_test_cards.py from the bundled DejaVu Sans Mono\n'
        ' * Bold (fonts/, licence beside it): font units, y down from the baseline. */\n'
        'export const GLYPHS = Object.freeze(' + body + ');\n')


# ---------------------------------------------------------------------------
# Test cards: 480 x 920 units = the 48 x 92 mm panel at 0.1 mm per unit
# ---------------------------------------------------------------------------

W, H = 480, 920
WHITE, LIGHT, DARK, BLACK = '#ffffff', '#aaaaaa', '#555555', '#000000'


def card(off_palette=False):
    e = []
    add = e.append
    title, _ = text_path('VECTOR TEST', 24, 62, 44)
    add(f'<path d="{title}" fill="{BLACK}"/>')
    sub, _ = text_path('4 DRIVE LEVELS · ANY SVG', 24, 92, 20)
    add(f'<path d="{sub}" fill="{DARK}"/>')

    # The four drive levels, labelled (and, off palette, a fifth grey)
    greys = [WHITE, LIGHT, DARK, BLACK] if not off_palette else [WHITE, LIGHT, '#777777', BLACK]
    for i, (fill, label) in enumerate(zip(greys, ['255', '170', '85' if not off_palette else '119', '0'])):
        x = 24 + i * 110
        add(f'<rect x="{x}" y="110" width="100" height="56" rx="8" fill="{fill}" stroke="{BLACK}" stroke-width="2"/>')
        t, tw = text_path(label, 0, 0, 20)
        t, _ = text_path(label, x + 50 - tw / 2, 190, 20)
        add(f'<path d="{t}" fill="{BLACK}"/>')

    # Space for the turning Siemens star (test-star.svg), centred at (240, 330)
    add(f'<circle cx="240" cy="330" r="128" fill="none" stroke="{DARK}" stroke-width="3"/>')

    # Two pentagrams: nonzero (filled centre) and evenodd (hollow centre)
    star = 'M0 -60L35.3 48.5L-57.1 -18.5H57.1L-35.3 48.5Z'
    add(f'<path transform="translate(120 540)" d="{star}" fill="{DARK}" fill-rule="nonzero"/>')
    add(f'<path transform="translate(360 540)" d="{star}" fill="{DARK}" fill-rule="evenodd"/>')
    for x, label in [(120, 'NONZERO'), (360, 'EVENODD')]:
        t, tw = text_path(label, 0, 0, 16)
        t, _ = text_path(label, x - tw / 2, 614, 16)
        add(f'<path d="{t}" fill="{BLACK}"/>')

    # Rings: stroke widths 0.1, 0.2, 0.4 and 0.8 mm
    for r, w, c in [(22, 1, BLACK), (40, 2, DARK), (58, 4, BLACK), (78, 8, DARK)]:
        add(f'<circle cx="120" cy="730" r="{r}" fill="none" stroke="{c}" stroke-width="{w}"/>')

    # A donut (a hole by evenodd), with a rotated square drawn over it: drawing order
    donut_fill = LIGHT if not off_palette else 'url(#fade)'
    if off_palette:
        add('<defs><linearGradient id="fade"><stop offset="0" stop-color="#fff"/><stop offset="1" stop-color="#000"/></linearGradient></defs>')
    add(f'<path d="M360 650a80 80 0 1 0 0.01 0ZM360 690a40 40 0 1 0 0.01 0Z" fill="{donut_fill}" fill-rule="evenodd" stroke="{BLACK}" stroke-width="3"/>')
    add(f'<rect x="-30" y="-30" width="60" height="60" transform="translate(410 790) rotate(30)" fill="{DARK}" stroke="{BLACK}" stroke-width="2" stroke-linejoin="round"/>')

    # A cubic and a quadratic curve, round caps; a sharp zigzag with miter joins
    add(f'<path d="M24 850C90 790 150 910 230 850S360 800 456 850" fill="none" stroke="{BLACK}" stroke-width="6" stroke-linecap="round"/>')
    add(f'<path d="M24 880Q60 860 96 880T168 880" fill="none" stroke="{DARK}" stroke-width="3"/>')
    add(f'<polyline points="196,896 216,866 236,896 256,866 276,896" fill="none" stroke="{BLACK}" stroke-width="4" stroke-linejoin="miter"/>')

    # Hairlines: 0.05, 0.1 and 0.2 mm
    for i, w in enumerate([0.5, 1, 2]):
        y = 872 + i * 12
        add(f'<line x1="300" y1="{y}" x2="456" y2="{y}" stroke="{BLACK}" stroke-width="{w}"/>')

    # Small text: 1.6 mm and 1.0 mm tall em
    t, _ = text_path('THE QUICK BROWN FOX 0123', 24, 912, 16)
    add(f'<path d="{t}" fill="{BLACK}"/>')

    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">\n'
            + '\n'.join(e) + '\n</svg>\n')


def siemens_star(spokes=24, r=118):
    import math
    d = []
    for i in range(spokes):
        a0 = 2 * math.pi * i / spokes
        a1 = 2 * math.pi * (i + 0.5) / spokes
        d.append(f'M0 0L{r * math.cos(a0):.3f} {r * math.sin(a0):.3f}A{r} {r} 0 0 1 {r * math.cos(a1):.3f} {r * math.sin(a1):.3f}Z')
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="-120 -120 240 240" width="240" height="240">\n'
            f'<path d="{"".join(d)}" fill="{BLACK}"/>\n'
            f'<circle r="10" fill="{WHITE}" stroke="{BLACK}" stroke-width="2"/>\n</svg>\n')


if __name__ == '__main__':
    write_glyphs()
    (APP / 'content' / 'test-card.svg').write_text(card())
    (APP / 'content' / 'test-card-off-palette.svg').write_text(card(off_palette=True))
    (APP / 'content' / 'test-star.svg').write_text(siemens_star())
    print('wrote content/glyphs.js, test-card.svg, test-card-off-palette.svg, test-star.svg')
